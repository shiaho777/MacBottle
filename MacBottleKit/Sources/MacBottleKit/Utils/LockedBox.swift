import Foundation

/// One lock, one value. Replaces the `nonisolated(unsafe) static var` plus
/// `NSLock` pairs that each cache used to hand-roll, so every shared
/// mutable cache goes through the same, auditable critical section.
public final class LockedBox<Value>: @unchecked Sendable {
    private let lock = NSLock()
    private var value: Value

    public init(_ value: Value) {
        self.value = value
    }

    @discardableResult
    public func withLock<T>(_ body: (inout Value) throws -> T) rethrows -> T {
        lock.lock()
        defer { lock.unlock() }
        return try body(&value)
    }
}
